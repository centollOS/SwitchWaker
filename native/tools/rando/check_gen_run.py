#!/usr/bin/env python3
"""A seed generated in the game's menu against wwrando (docs/RANDOMIZER_PLAN.md step R4.3).

    python3 -I native/tools/rando/check_gen_run.py [--seed S] [--run-dir DIR] [--keep]

1. Runs the in-game smoke that presses the options menu's Generate row:
     native/tools/run.sh rando --stage sea:44:206 --env COS_RANDO_SMOKE=gen --env COS_RANDO_SEED=<S>
   into its own run directory (exit 0 required). With --run-dir DIR it reads an earlier run instead.
2. Takes the sidecar the run wrote in its card folder and the logs in <run dir>/user/rando (the
   smoke prints both paths) and checks them like check_seeds.py --golden does for the CLI:
   ww_verify passes, and against wwrando 1.10.0_9775811 (dry) on the same seed at its default
   options: the placement (seed, permalink, options, decisions, every location in order), the pigs
   bitfield, and the logs (non-spoiler byte-identical, spoiler aside from its Hints section) after
   the trailer "Generated by SwitchWaker dev".

Exit 0 all held, 1 a check failed, 2 usage or setup error (needs the oracle venv:
native/tools/rando/setup_oracle.sh, and COS_DISC for the run).
"""
import os
import sys
sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import oracle_common as oc  # noqa: E402

import argparse  # noqa: E402
import re  # noqa: E402
import shutil  # noqa: E402
import subprocess  # noqa: E402
import tempfile  # noqa: E402

GAME_VERSION = "dev"  # the Mac build's version in the log trailer (pc_rando_menu.cpp)


def main():
  ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
  ap.add_argument("--seed", default="TestSeed1")
  ap.add_argument("--run-dir", help="read this earlier run of the smoke instead of running it")
  ap.add_argument("--keep", action="store_true", help="keep the temporary folder")
  a = ap.parse_args()

  oc.bootstrap()
  import check_seeds
  check_seeds.CLI_VERSION = GAME_VERSION  # strip_trailer's version
  check_seeds.worker_init()

  tmp = tempfile.mkdtemp(prefix="cos_rando_gen_")
  try:
    run_dir = a.run_dir
    if run_dir is None:
      run_dir = os.path.join(tmp, "run")
      cmd = [os.path.join(oc.REPO_ROOT, "native", "tools", "run.sh"), "rando", "--stage", "sea:44:206",
             "--uncapped", "--quiet", "--run-dir", run_dir, "--env", "COS_RANDO_SMOKE=gen",
             "--env", f"COS_RANDO_SEED={a.seed}"]
      rc = subprocess.call(cmd)
      if rc != 0:
        print(f"FAIL the gen smoke exited {rc} ({run_dir}/run.log)")
        return 1
    log = check_seeds.read_text(os.path.join(run_dir, "run.log")) or ""
    paths = dict(re.findall(r"^\[cos\] rando-smoke gen: (sidecar|spoiler) (.+)$", log, flags=re.M))
    if "sidecar" not in paths or "spoiler" not in paths or "rando-smoke gen: PASS" not in log:
      print(f"FAIL the run did not pass or name its files ({run_dir}/run.log)")
      return 1
    # check_seeds.check_one reads the logs next to the placement JSON.
    ours = os.path.join(tmp, "ours")
    os.makedirs(ours)
    seed = check_seeds.sanitize(a.seed)
    shutil.copy(paths["sidecar"], os.path.join(ours, seed + ".json"))
    for name in check_seeds.log_names(seed):
      src = os.path.join(os.path.dirname(paths["spoiler"]), name)
      if os.path.exists(src):
        shutil.copy(src, os.path.join(ours, name))
    _, problems = check_seeds.check_one((seed, {}, os.path.join(ours, seed + ".json"), None, tmp, True,
                                          False))  # hints: the menu generates without them
    for p in problems:
      print(f"FAIL {seed}: {p}")
    if problems:
      return 1
    print(f"ok {seed}: the menu's sidecar {os.path.basename(paths['sidecar'])} and logs equal wwrando's "
          "(ww_verify passed; hints aside)")
    return 0
  finally:
    if a.keep:
      print(f"kept {tmp}")
    else:
      shutil.rmtree(tmp, ignore_errors=True)


if __name__ == "__main__":
  sys.exit(main())
