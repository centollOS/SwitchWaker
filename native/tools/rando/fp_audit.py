#!/usr/bin/env python3
"""fp_audit.py - fingerprint audit of every dzx and event patcher, USA and EUR (plan step R7.6b).

    python3 -I native/tools/rando/fp_audit.py [--region usa|eur|both] [--placement P] [--dry]

Runs the fpaudit smoke (native/src/pc/harness/smokes/pc_rando_smoke_fpaudit.cpp) on each region's
build and disc: every stage.dzs, room.dzr and event_list.dat of the disc goes through the archive
hook's whole patcher chain with the placement's seed. Each patcher checks its own fingerprints (D9)
and logs what it left vanilla; this script reads those lines from the run log and attributes each to
the file the smoke was patching.

  --placement P   rotation-all (default): R0.6's rotation placement (every location gets an item of
                  another class) with every stage-data option on: the non-item decisions (entrances
                  of all 6 kinds, required bosses, enemies, enemy palettes, charts, starting island)
                  of native/check/rando/fixtures/R7_6b_all_options.json, a seed generated by
                  cos_rando_cli with every option on (trap chests, chest type matches contents,
                  warp pots, KoRL hints and the rest); all-options: that seed itself; rotation,
                  identity: R0.6's fixtures as they are; or a placement JSON path
  --region R      usa (build/native-mac, GZLE01), eur (build/native-mac-eur, GZLP01) or both (default)
  --usa-disc, --eur-disc   the discs (default $COS_DISC / ~/Documents/windwaker/GZLE01.iso and
                  ~/Documents/windwaker/GZLP01/GZLP01.iso)
  --out DIR       runs and the composed placement (default build/rando-fpaudit)

A patcher line is a problem when it reports a fingerprint mismatch, a missing entry or chunk, a
refusal, a failure or something "left vanilla" / "stays vanilla" (a count of 0 is not). Result per
region: the problem lines with their file; with both regions, the EUR lines that the USA disc does not
have too. Exit 0 when every run's smoke passed and no region has a problem line (with both: none on
EUR beyond the USA's, and none on USA); 1 otherwise; 2 usage. Mac only, dev time; standard library.
"""
import argparse
import json
import os
import re
import subprocess
import sys
import time

TOOLS = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO = os.path.normpath(os.path.join(TOOLS, "..", ".."))
RUN_SH = os.path.join(TOOLS, "run.sh")
FIXTURES = os.path.join(REPO, "native", "check", "rando", "fixtures")
ALL_OPTIONS = os.path.join(FIXTURES, "R7_6b_all_options.json")
REGIONS = {
    "usa": ("build/native-mac", os.environ.get("COS_DISC") or "~/Documents/windwaker/GZLE01.iso"),
    "eur": ("build/native-mac-eur", "~/Documents/windwaker/GZLP01/GZLP01.iso"),
}
BOOT = "Abship:2:0"
# Fields of a placement that are not item locations (schema format 1).
NON_ITEM = ("options", "extra_starting_items", "charts", "required_boss_locations", "entrances",
            "starting_island_room", "enemies", "palettes", "hints", "captured_pigs_bitfield")

RE_FILE = re.compile(r"\[cos\] rando-smoke fpaudit: file (\S+) (\d+)$")
RE_BEGIN = re.compile(r"\[cos\] rando-smoke fpaudit: begin")
RE_END = re.compile(r"\[cos\] rando-smoke fpaudit: end: (.*)$")
RE_SMOKE_END = re.compile(r"\[cos\] rando-smoke fpaudit: (PASS|FAIL)")
RE_PATCHER = re.compile(r"\[cos\] rando[ :]")
RE_BAD = re.compile(r"mismatch|missing|refus|fail|not found|no such|vanilla|cannot|does not parse|unusable|"
                    r"skipped|not the vanilla|errors|conflicts", re.I)
# "<n> left vanilla", "<n> mismatches", ...: a problem only when n > 0.
RE_COUNT = re.compile(r"(\d+) (left vanilla|mismatches|errors|conflicts|failed|skipped)")


def die(msg, code=2):
    print("fp-audit: " + msg, file=sys.stderr)
    sys.exit(code)


def compose(name, out_dir):
    if name in ("rotation", "identity"):
        return os.path.join(FIXTURES, "R0_6_%s.json" % name)
    if name == "all-options":
        return ALL_OPTIONS
    if name != "rotation-all":
        path = os.path.abspath(name)
        if not os.path.isfile(path):
            die("no placement %s" % name)
        return path
    with open(os.path.join(FIXTURES, "R0_6_rotation.json")) as f:
        rot = json.load(f)
    with open(ALL_OPTIONS) as f:
        allopt = json.load(f)
    for k in NON_ITEM:
        if k in allopt:
            rot[k] = allopt[k]
        else:
            rot.pop(k, None)
    rot["seed"] = "FpAuditRotationAll"
    rot["permalink"] = allopt["permalink"]  # the options' permalink (its seed name differs; not checked)
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "rotation_all_options.json")
    with open(path, "w") as f:
        json.dump(rot, f, indent=1)
    return path


def problem(line):
    if not RE_PATCHER.search(line) or "rando-smoke" in line:
        return False
    counts = RE_COUNT.findall(line)
    if counts:
        rest = RE_COUNT.sub("", line)
        return any(int(n) > 0 for n, _ in counts) or bool(RE_BAD.search(rest.split(":", 1)[-1]))
    return bool(RE_BAD.search(line))


def audit(log):
    """(problems [(file, line)], summary, smoke result, files)"""
    cur = "-"
    inside = False
    out = []
    summary = None
    result = None
    files = 0
    for raw in log.splitlines():
        line = raw.rstrip()
        if RE_BEGIN.search(line):
            inside = True
            continue
        m = RE_END.search(line)
        if m:
            summary = m.group(1)
            inside = False
            continue
        m = RE_SMOKE_END.search(line)
        if m:
            result = m.group(1)
            continue
        m = RE_FILE.search(line)
        if m:
            cur = m.group(1)
            files += 1
            continue
        if inside and problem(line):
            i = line.find("[cos]")
            out.append((cur, line[i:]))
    return out, summary, result, files


def run_region(region, placement, args):
    build, disc = REGIONS[region]
    disc = os.path.abspath(os.path.expanduser(args.usa_disc if region == "usa" and args.usa_disc else
                                              args.eur_disc if region == "eur" and args.eur_disc else disc))
    exe = os.path.join(REPO, build, "switchwaker")
    run_dir = os.path.join(args.out, "%s-%s" % (region, time.strftime("%Y%m%d-%H%M%S")))
    cmd = [RUN_SH, "rando", "--stage", BOOT, "--timeout", "600", "--stall", "120",
           "--env", "COS_RANDO_SMOKE=fpaudit", "--env", "COS_RANDO_PLACEMENT=" + placement,
           "--disc", disc, "--quiet", "--run-dir", run_dir]
    env = dict(os.environ, COS_BUILD_DIR=build)
    if args.dry:
        print("fp-audit: %s: COS_BUILD_DIR=%s %s" % (region, build, " ".join(cmd)))
        return None
    if not os.path.isfile(exe):
        die("%s: no %s (build it first)" % (region, os.path.relpath(exe, REPO)))
    if not os.path.isfile(disc):
        die("%s: no disc %s" % (region, disc))
    print("fp-audit: %s: %s built %s" % (region, os.path.relpath(exe, REPO), time.strftime(
        "%Y-%m-%d %H:%M:%S", time.localtime(os.path.getmtime(exe)))), flush=True)
    t0 = time.time()
    subprocess.run(cmd, cwd=REPO, env=env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    try:
        with open(os.path.join(run_dir, "exit_code.txt")) as f:
            rc = int(f.read().strip())
    except (OSError, ValueError):
        rc = -1
    try:
        with open(os.path.join(run_dir, "run.log"), errors="replace") as f:
            log = f.read()
    except OSError:
        log = ""
    probs, summary, result, files = audit(log)
    print("fp-audit: %s: exit %d, %.0f s, smoke %s; %s; %d problem line(s); run %s" % (
        region, rc, time.time() - t0, result or "no result", summary or "no end line (%d files)" % files,
        len(probs), os.path.relpath(run_dir, REPO)), flush=True)
    return {"rc": rc, "ok": rc == 0 and result == "PASS" and summary is not None, "problems": probs}


def norm(line):
    return re.sub(r"\s+", " ", line)


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0],
                                 formatter_class=argparse.RawDescriptionHelpFormatter, epilog=__doc__)
    ap.add_argument("--region", default="both", choices=["usa", "eur", "both"])
    ap.add_argument("--placement", default="rotation-all")
    ap.add_argument("--usa-disc")
    ap.add_argument("--eur-disc")
    ap.add_argument("--out", default=os.path.join(REPO, "build", "rando-fpaudit"))
    ap.add_argument("--dry", action="store_true")
    args = ap.parse_args(argv)
    args.out = os.path.abspath(args.out)
    placement = compose(args.placement, args.out)
    print("fp-audit: placement %s" % os.path.relpath(placement, REPO))
    regions = ["usa", "eur"] if args.region == "both" else [args.region]
    res = {r: run_region(r, placement, args) for r in regions}
    if args.dry:
        return 0
    ok = all(v["ok"] for v in res.values())
    for r in regions:
        for f, line in res[r]["problems"][:60]:
            print("fp-audit:   %s %s: %s" % (r, f, line))
    if args.region == "both":
        usa = {(f, norm(l)) for f, l in res["usa"]["problems"]}
        eur_only = [(f, l) for f, l in res["eur"]["problems"] if (f, norm(l)) not in usa]
        print("fp-audit: EUR: %d problem line(s), %d not on USA; USA: %d" % (
            len(res["eur"]["problems"]), len(eur_only), len(res["usa"]["problems"])))
        ok = ok and not eur_only and not res["usa"]["problems"]
    else:
        ok = ok and not res[regions[0]]["problems"]
    print("fp-audit: %s" % ("PASS" if ok else "FAIL"))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
