#!/usr/bin/env python3
"""Permalink, seed-hash and option-default vectors for cos_rando_test_R1_2 (plan step R1.2).

    python3 -I native/tools/rando/gen_permalink_vectors.py [out.txt]
    python3 -I native/tools/rando/gen_permalink_vectors.py --words [out.inc]

Default output: native/check/rando/fixtures/R1_2_permalinks.txt. The output is deterministic (a fixed
Python Random drives the option sets), so regenerating must give a byte-identical file:

    python3 -I native/tools/rando/gen_permalink_vectors.py /tmp/x.txt && \
        diff /tmp/x.txt native/check/rando/fixtures/R1_2_permalinks.txt

--words writes the seedgen word lists (seedgen/{adjectives,nouns,names}.txt, MIT) as C string
tables for pc_rando_seedgen.cpp, default native/src/pc/features/rando/generated/
pc_rando_seedgen_words.inc (checked in; regenerate and diff the same way).

It runs wwrando 1.10.0_9775811 (ref/wwrando, see README.md) and writes a tab-separated text file:

    version   <VERSION>
    option    <name> <kind> <permalink> <hidden> <unbeatable> <min> <max> <default>   (77, Options.all() order)
    regular   <item>                       (REGULAR_ITEMS, 56, permalink bit order)
    progressive <item>                     (sorted unique PROGRESSIVE_ITEMS, 8)
    case      <n>                          then, per case:
      input_seed <raw seed text>           (what the user typed; may hold invalid characters)
      key        <SEED_KEY used>           (wwrando's do_not_generate_spoiler_log key; "" in source)
      in         <name> <value>            the options given to encode_permalink (permalink options)
      seed       <sanitized seed>
      permalink  <base64>
      hash       <seed hash>               get_seed_hash() for this permalink and key
      intseed    <md5 hex>                 md5 of seed (+key when do_not_generate_spoiler_log)
      out        <name> <value>            all 77 options after decode_permalink(permalink) from defaults
    end

<kind> is bool, enum, int, str, list or dict. Values: bool 0/1, enum its string value, int decimal,
list items joined by '|', str as is, dict as JSON. Cases 0-49 are random option sets (the first is
the default options); cases with a non-empty key exercise the seed key in the hash. Exit 0 written, 2
setup error.
"""
import os
import sys
sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import oracle_common as oc  # noqa: E402

import contextlib  # noqa: E402
import json  # noqa: E402
import random  # noqa: E402
import types  # noqa: E402
import typing  # noqa: E402
from enum import StrEnum  # noqa: E402

N_CASES = 50
VECTOR_SEED = 0x52312E32  # "R1.2"


def kind_of(opt):
  t = typing.get_origin(opt.type) or opt.type
  if t is bool:
    return "bool"
  if isinstance(t, type) and issubclass(t, StrEnum):
    return "enum"
  if t is int:
    return "int"
  if t is str:
    return "str"
  if t is list:
    return "list"
  if t is dict:
    return "dict"
  raise SystemExit(f"unknown option type {opt.type} for {opt.name}")


def fmt(kind, v):
  if kind == "bool":
    return "1" if v else "0"
  if kind == "enum":
    return str(v.value if hasattr(v, "value") else v)
  if kind == "int":
    return str(int(v))
  if kind == "list":
    return "|".join(v)
  if kind == "dict":
    return json.dumps(v, sort_keys=True)
  return str(v)


def random_seed_text(rng, adjectives, nouns):
  r = rng.randrange(6)
  if r == 0:
    return "".join(w.capitalize() for w in rng.sample(adjectives, 2)) + rng.choice(nouns).capitalize()
  if r == 1:
    return str(rng.randrange(10 ** 9))
  if r == 2:  # invalid characters, padding whitespace, too long
    alphabet = "abcXYZ019-_'%.!@# /\\éü~+"
    return "  " + "".join(rng.choice(alphabet) for _ in range(rng.randrange(1, 70))) + " \t"
  if r == 3:
    return "".join(rng.choice("abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789") for _ in range(rng.randrange(40, 60)))
  if r == 4:
    return rng.choice(["TestSeed1", "pytestseed", "abc", "3304751", "x"])
  return "Seed%d's.%%-_x" % rng.randrange(1000)


def c_string(s):
  return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_words(out_path):
  from wwrando_paths import SEEDGEN_PATH
  out = ["// Generated by native/tools/rando/gen_permalink_vectors.py --words from wwrando 1.10.0_9775811",
         "// seedgen/*.txt (MIT). Do not edit. Included by pc_rando_seedgen.cpp."]
  for name in ("adjectives", "nouns", "names"):
    with open(os.path.join(SEEDGEN_PATH, name + ".txt")) as f:
      words = f.read().splitlines()
    out.append(f"static const char* const kSeedgen_{name}[] = {{")
    out += [f"    {c_string(w)}," for w in words]
    out.append("};")
  data = "\n".join(out) + "\n"
  with open(out_path, "w", encoding="utf-8", newline="\n") as f:
    f.write(data)
  print(f"wrote {out_path}", file=sys.stderr)


def main():
  if len(sys.argv) > 1 and sys.argv[1] == "--words":
    oc.bootstrap()
    write_words(sys.argv[2] if len(sys.argv) > 2 else os.path.join(
      oc.REPO_ROOT, "native", "src", "pc", "features", "rando", "generated", "pc_rando_seedgen_words.inc"))
    return
  out_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
    oc.REPO_ROOT, "native", "check", "rando", "fixtures", "R1_2_permalinks.txt")
  oc.bootstrap()
  with contextlib.redirect_stdout(sys.stderr):
    import randomizer
    from randomizer import WWRandomizer
    from options.wwrando_options import Options
    from wwr_ui.inventory import REGULAR_ITEMS, PROGRESSIVE_ITEMS, INVENTORY_ITEMS
    from version import VERSION
    from wwrando_paths import SEEDGEN_PATH

  with open(os.path.join(SEEDGEN_PATH, "adjectives.txt")) as f:
    adjectives = f.read().splitlines()
  with open(os.path.join(SEEDGEN_PATH, "nouns.txt")) as f:
    nouns = f.read().splitlines()

  lines = [f"version\t{VERSION}"]
  defaults = Options()
  for opt in Options.all():
    k = kind_of(opt)
    lines.append("\t".join([
      "option", opt.name, k, str(int(opt.permalink)), str(int(opt.hidden)), str(int(opt.unbeatable)),
      "" if opt.minimum is None else str(opt.minimum), "" if opt.maximum is None else str(opt.maximum),
      fmt(k, defaults[opt.name])]))
  for item in REGULAR_ITEMS:
    lines.append(f"regular\t{item}")
  for item in sorted(set(PROGRESSIVE_ITEMS)):
    lines.append(f"progressive\t{item}")

  rng = random.Random(VECTOR_SEED)
  for case in range(N_CASES):
    opts = Options()
    if case > 0:
      for opt in Options.all():
        if not opt.permalink:
          continue
        k = kind_of(opt)
        if k == "bool":
          opts[opt.name] = rng.random() < 0.5
        elif k == "enum":
          opts[opt.name] = rng.choice(list(opt.type))
        elif k == "int":
          opts[opt.name] = rng.randint(opt.minimum, opt.maximum)
        elif opt.name == "starting_gear":
          start = [i for i in REGULAR_ITEMS if rng.random() < 0.3]
          for item in sorted(set(PROGRESSIVE_ITEMS)):
            start += [item] * rng.randint(0, PROGRESSIVE_ITEMS.count(item))
          rest = list(INVENTORY_ITEMS)
          for item in start:
            rest.remove(item)
          opts.starting_gear = sorted(start)
          opts.randomized_gear = sorted(rest)
    key = "" if case % 5 != 4 else "TestSeedKey%d" % case
    seed_text = "TestSeed1" if case == 0 else random_seed_text(rng, adjectives, nouns)

    randomizer.SEED_KEY = key
    permalink = WWRandomizer.encode_permalink(seed_text, opts)
    seed = WWRandomizer.sanitize_seed(seed_text)
    fake = types.SimpleNamespace(
      permalink=permalink, options=opts,
      convert_string_to_integer_md5=lambda s: WWRandomizer.convert_string_to_integer_md5(None, s))
    seed_hash = WWRandomizer.get_seed_hash(fake)
    seed_string = seed + (key if opts.do_not_generate_spoiler_log else "")
    intseed = "%032x" % WWRandomizer.convert_string_to_integer_md5(None, seed_string)
    with contextlib.redirect_stdout(sys.stderr):
      dec_seed, dec = WWRandomizer.decode_permalink(permalink)
    assert dec_seed == seed

    if "\t" in seed_text or "\n" in seed_text:
      seed_text = seed_text.replace("\t", " ").replace("\n", " ")
    lines.append(f"case\t{case}")
    lines.append(f"input_seed\t{seed_text}")
    lines.append(f"key\t{key}")
    for opt in Options.all():
      if opt.permalink:
        lines.append(f"in\t{opt.name}\t{fmt(kind_of(opt), opts[opt.name])}")
    lines.append(f"seed\t{seed}")
    lines.append(f"permalink\t{permalink}")
    lines.append(f"hash\t{seed_hash}")
    lines.append(f"intseed\t{intseed}")
    for opt in Options.all():
      lines.append(f"out\t{opt.name}\t{fmt(kind_of(opt), dec[opt.name])}")
    lines.append("end")
  randomizer.SEED_KEY = ""

  data = "\n".join(lines) + "\n"
  if out_path == "-":
    sys.stdout.write(data)
  else:
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
      f.write(data)
    print(f"wrote {out_path}: {N_CASES} cases", file=sys.stderr)


if __name__ == "__main__":
  main()
