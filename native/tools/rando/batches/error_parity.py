#!/usr/bin/env python3
"""R9.3: full-message error parity between our generator and wwrando (docs/RANDOMIZER_PLAN.md).

    python3 -I native/tools/rando/batches/error_parity.py [--cli PATH] [--seed S] [--out DIR]

check_seeds.py --golden compares only the first line of an error (the CLI's "FAIL <seed>: <line>").
This tool runs a fixed set of option combos, takes our whole message from the CLI's Error Log
("Error on seed <S>:" up to the trailer) and requires it to equal str(exception) of wwrando
1.10.0_9775811 on the same seed and options; a combo that generates on one side must generate on
the other. The combos cover "Not enough progress locations to place all progress items." with and
without the "Maximum Required Bosses Mode banned locations" line, and required-bosses errors.
Exit 0 all equal, 1 a difference, 2 usage or setup error.
"""
import os
import sys
sys.dont_write_bytecode = True
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import oracle_common as oc  # noqa: E402

import argparse  # noqa: E402
import dataclasses  # noqa: E402
import subprocess  # noqa: E402
import tempfile  # noqa: E402


def combos():
  from options.wwrando_options import Options
  prog = [f.name for f in dataclasses.fields(Options) if f.name.startswith("progression_")]

  def only(*cats):
    return {p: p in ["progression_" + c for c in cats] for p in prog}
  return {
    "all_off": only(),
    "only_mail": only("mail"),
    "only_misc": only("misc"),
    "only_dungeons_rb6": dict(only("dungeons"), required_bosses=True, num_required_bosses=6),
    "only_dungeons_rb1": dict(only("dungeons"), required_bosses=True, num_required_bosses=1),
    "dungeons_mail_rb1": dict(only("dungeons", "mail"), required_bosses=True, num_required_bosses=1),
    "dungeons_misc_rb2": dict(only("dungeons", "misc"), required_bosses=True, num_required_bosses=2),
    "no_dungeons_rb4": {"progression_dungeons": False, "required_bosses": True, "num_required_bosses": 4},
    "default_rb6": {"required_bosses": True, "num_required_bosses": 6},
    "swordless_all_off": dict(only(), sword_mode="Swordless"),
  }


def cli_value(v):
  return "true" if v is True else "false" if v is False else str(v)


def main():
  ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
  ap.add_argument("--cli", default=os.path.join(oc.REPO_ROOT, "build", "native-mac", "cos_rando_cli"))
  ap.add_argument("--seed", default="X1Seed")
  ap.add_argument("--out", help="keep the logs here (default: a temporary folder)")
  a = ap.parse_args()
  oc.bootstrap()
  oc.set_seed_key("SwitchWaker-rando-key-1")
  base = a.out or tempfile.mkdtemp(prefix="error_parity_")
  bad = 0
  for name, vals in combos().items():
    out = os.path.join(base, name)
    os.makedirs(out, exist_ok=True)
    log = os.path.join(out, f"WW Random {a.seed} - Error Log.txt")
    if os.path.exists(log):
      os.remove(log)
    cmd = [a.cli, "--out", out, "--allow-missing-hints"] + [f"{k}={cli_value(v)}" for k, v in vals.items()] + [a.seed]
    p = subprocess.run(cmd, capture_output=True, text=True)
    if p.returncode not in (0, 1):
      sys.stderr.write(p.stdout + p.stderr)
      oc.die(f"{name}: cos_rando_cli exited {p.returncode}")
    ours = None
    if p.returncode == 1:
      text = open(log).read() if os.path.exists(log) else ""
      marker = f"Error on seed {a.seed}:\n"
      ours = text.split(marker, 1)[1].rsplit("Generated by SwitchWaker", 1)[0].strip() if marker in text \
          else p.stdout.strip()
    try:
      r = oc.make_randomizer(a.seed, oc.make_options(vals), logs_dir=os.path.join(out, "ww"))
      oc.randomize(r)
      theirs = None
    except Exception as e:  # wwrando raised
      theirs = str(e).strip()
    same = ours == theirs
    bad += not same
    first = lambda s: "generated" if s is None else s.split("\n")[0] + (" [...]" if "\n" in s else "")  # noqa: E731
    print(f"{'ok  ' if same else 'DIFF'} {name}: {first(theirs)}")
    if not same:
      print(f"     ours:    {ours!r}\n     wwrando: {theirs!r}")
  print(f"error_parity: {len(combos())} combos, {len(combos()) - bad} equal, {bad} differ")
  return 1 if bad else 0


if __name__ == "__main__":
  sys.exit(main())
