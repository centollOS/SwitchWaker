// pc_rando_spoiler.h - progression spheres and the seed's logs (docs/RANDOMIZER_PLAN.md step R1.5): a
// port of wwrando 1.10.0_9775811's
//   - ItemRandomizer.calculate_playthrough_progression_spheres (randomizers/items.py);
//   - WWRandomizer.get_log_header / write_spoiler_log / write_non_spoiler_log / write_error_log
//     (randomizer.py) and the write_to_spoiler_log / write_to_non_spoiler_log of every randomizer
//     (items, extra starting items, required bosses, starting island, entrances, charts, hints).
//
// Pure C++ (no game headers, no file I/O): cos_rando_core, the unit tests and the Mac CLI link it.
// The functions return the log text; the caller writes it (decision D5: <userPath>/rando/, the file
// names of logFileName, then logTrailer's line, which wwrando does not have).
//
// Exactness: for the same seed, options and decisions the text is byte-identical to the file wwrando
// writes (the R1.5 fixture checks it). The logs are built from:
//   - the item fill's Logic (done_item_locations, prerandomization_item_locations, all_progress_items,
//     and logic.state(): entrances, charts, required-bosses banned locations, extra starting items);
//   - SpoilerInput: what the other randomizers decided that the Logic does not hold.
// One thing is not ported: a non-empty custom_colors option is left out of the header (wwrando lists
// only the colors that differ from the player model's defaults, which come from the model files).
#pragma once

#include <string>
#include <utility>
#include <vector>

#include "pc_rando_logic.h"
#include "pc_rando_options.h"

namespace pcr {

// One progression sphere: location -> item, Python dict order. A sphere also holds the pseudo
// entries "<Dungeon> - Boss" -> "Defeat <Boss>" and "Ganon's Tower - Rooftop" -> "Defeat Ganondorf".
struct SphereEntry {
    std::string location;
    std::string item;
};
using ProgressionSphere = std::vector<SphereEntry>;

// The decisions the logs print that are not in the Logic.
struct SpoilerInput {
    std::string seed;      // WWRandomizer.seed (sanitized)
    std::string permalink; // empty: no Permalink line
    std::string seedHash;  // empty: no Seed Hash line
    // boss_reqs (printed when options.required_bosses).
    std::vector<std::string> requiredDungeons;
    std::vector<std::string> bannedDungeons;
    std::vector<std::string> requiredBosses; // "Gohma", ... (the spheres' required-boss split)
    // starting_island.room_number (44: Outset, wwrando's vanilla start).
    int startingIslandRoom = 44;
    // entrances.nesting_enabled and nested_entrance_paths (exit last, as wwrando stores them).
    bool nestingEnabled = false;
    std::vector<std::vector<std::string>> nestedEntrancePaths;
    // HintsRandomizer.write_to_spoiler_log's rows (place, reward): the Savage Labyrinth floors 30 and 50
    // (savageLabyrinthHintRows), the Big Octo Great Fairy, then each hint placement's hints.
    std::vector<std::pair<std::string, std::string>> hints;
    // WWRandomizer.randomize_items (false only with wwrando's --noitemrando debug flag).
    bool randomizeItems = true;
};

// calculate_playthrough_progression_spheres on the Logic the item fill filled. It builds its own
// fresh Logic from logic.options() and logic.state() (Logic(self.rando)), as wwrando does. False (and
// *err: "Failed to calculate progression spheres", or a Logic error) where wwrando raises.
bool calculateProgressionSpheres(Logic& logic, const SpoilerInput& in, std::vector<ProgressionSphere>& out,
                                 std::string* err);

// get_log_header (Version, Permalink, Seed Hash, Seed, options) with its "\n\n\n".
std::string logHeader(const Options& o, const SpoilerInput& in);
// write_spoiler_log's text. False (and *err) when the spheres cannot be calculated.
bool spoilerLog(Logic& logic, const SpoilerInput& in, std::string& out, std::string* err);
// write_non_spoiler_log's text: the header, then the progress and non-progress locations.
std::string nonSpoilerLog(Logic& logic, const SpoilerInput& in);
// write_error_log's text: the header, then the message (wwrando passes
// "Error on seed <seed>:\n<exception>\n\n<traceback>").
std::string errorLog(const Options& o, const SpoilerInput& in, const std::string& message);

// The Savage Labyrinth rows of the hints section (generate_savage_labyrinth_hint +
// check_item_can_be_hinted_at): the placed item, or "Nothing" when it cannot be hinted at.
void savageLabyrinthHintRows(Logic& logic, std::vector<std::pair<std::string, std::string>>& rows);

// "WW Random <seed> - Spoiler Log.txt" for kind "Spoiler Log", "Non-Spoiler Log" or "Error Log".
std::string logFileName(const std::string& seed, const char* kind);
// Decision D5's trailing line, appended after wwrando's text: "Generated by SwitchWaker <version>\n".
std::string logTrailer(const char* version);

// Helpers shared with the tests.
// Python's repr() of a str (the header's list values).
std::string pyRepr(const std::string& s);
// split_location_name_by_zone.
void splitLocationName(const std::string& name, std::string& zone, std::string& specific);
// EntranceRandomizer.write_to_spoiler_log's shorten_path_name.
std::string shortenEntrancePathName(const std::string& name);

} // namespace pcr
